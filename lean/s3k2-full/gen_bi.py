#!/usr/bin/env python3
"""Generate Lean data for the bivariate Gaiser kernel case (a = s + 4, k = s + t + 7).
usage: gen_bi.py JSON LRAT NAME SEG_SIZE"""
import sys, json
import sympy as sp
jf, lrat, name, SEG = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
N = name[0].upper() + name[1:]
J = json.load(open(jf)); R0 = J['region']; assert R0['mode'] == 'bi' and R0['A0'] == 4 and R0['B0'] == 3
s, t = sp.symbols('s t'); a = 4 + s; k = 7 + s + t
MON = {'1': sp.Integer(1), 'a': a, 'k': k, 'ak': a * k, 'k^2': k**2, 'ak^2': a * k**2, 'k^3': k**3}
def nested(expr):
    expr = sp.expand(expr)
    P = sp.Poly(expr, s, t)
    ds = P.degree(s) if not P.is_zero else 0
    out = []
    for i in range(ds + 1):
        qi = sp.Poly(sp.expand(sp.diff(expr, s, i).subs(s, 0) / sp.factorial(i)), t)
        co = [int(qi.coeff_monomial(t**j)) for j in range(qi.degree() + 1)] if not qi.is_zero else []
        out.append(co)
    while out and out[-1] == []: out.pop()
    return out
V = [nested(sum(c * MON[m] for c, m in zip(v, J['monomials']))) for v in J['vertices']]
# sanity: re-evaluate
import random
for _ in range(20):
    sv, tv = random.randint(0, 30), random.randint(0, 30)
    for v, P in zip(J['vertices'], V):
        av, kv = 4 + sv, 7 + sv + tv
        direct = sum(c * {'1': 1, 'a': av, 'k': kv, 'ak': av * kv, 'k^2': kv**2, 'ak^2': av * kv**2, 'k^3': kv**3}[m] for c, m in zip(v, J['monomials']))
        nest = sum(sv**i * sum(cj * tv**j for j, cj in enumerate(q)) for i, q in enumerate(P))
        assert direct == nest
E = [(u + 1, v + 1, w + 1) for (u, v, w) in J['edges']]
R = [i + 1 for i in J['red']]; B = [i + 1 for i in J['blue']]
L = lambda xs: '[' + ', '.join(map(str, xs)) + ']'
with open(f'RSN/Data/{N}.lean', 'w') as f:
    f.write('module\n\npublic import Init\n\n@[expose] public section\n\nnamespace RSN\n\n')
    f.write(f'/-- Bivariate case (generated by gen_bi.py from {jf.split("/")[-1]}): vertex polynomials in `(s, t)` with '
            f'`a = s + 4`, `k = s + t + 7`, as lists over powers of `s` of coefficient lists in `t`. -/\n')
    f.write(f'def {name}Verts : List (List (List Int)) := [\n' + ',\n'.join('  [' + ', '.join(L(q) for q in P) + ']' for P in V) + '\n]\n\n')
    f.write(f'def {name}Edges : List (Nat × Nat × Nat) := [\n' + ',\n'.join(f'  ({u}, {v}, {w})' for u, v, w in E) + '\n]\n\n')
    f.write(f'def {name}Reds : List Nat := {L(R)}\n\ndef {name}Blues : List Nat := {L(B)}\n\ndef {name}N : Nat := {len(V)}\n\nend RSN\n')
import segwriter
steps = segwriter.read_lrat(lrat)
nseg, nf = segwriter.write(name, N, steps, SEG, 10, f'RSN.Data.{N}', f'def {name}CNF : List Clause := caseCNF {name}N {name}Edges {name}Reds {name}Blues')
print('vertices', len(V), 'edges', len(E), 'reds', R, 'blues', B, 'steps', len(steps), 'segments', nseg, 'files', nf)

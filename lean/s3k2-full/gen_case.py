#!/usr/bin/env python3
"""Generate Lean data for one univariate Gaiser kernel case (k = t + K).
usage: gen_case.py JSON LRAT NAME SEG_SIZE
Writes RSN/Data/<Name>.lean (vertices in t-basis, edges/reds/blues 1-based) and
RSN/Data/<Name>Seg.lean + RSN/<Name>Unsat.lean (kernel-checked LRAT, segmented)."""
import sys, json
from math import comb
jf, lrat, name, SEG = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
N = name[0].upper() + name[1:]
J = json.load(open(jf)); assert J['region']['mode'] == 'uni'
K = J['region']['K']; assert J['monomials'] == ['1', 'k', 'k^2', 'k^3']
def shift(c):  # coefficients of p(t+K) in t
    out = [0] * 4
    for j, cj in enumerate(c):
        for i in range(j + 1): out[i] += cj * comb(j, i) * K ** (j - i)
    return out
V = [shift(c) for c in J['vertices']]
E = [(u + 1, v + 1, w + 1) for (u, v, w) in J['edges']]
R = [i + 1 for i in J['red']]; B = [i + 1 for i in J['blue']]
L = lambda xs: '[' + ', '.join(map(str, xs)) + ']'
with open(f'RSN/Data/{N}.lean', 'w') as f:
    f.write(f'module\n\npublic import Init\n\n@[expose] public section\n\nnamespace RSN\n\n')
    f.write(f'/-- Case `{J["region"]["case"]}` (generated by gen_case.py from {jf.split("/")[-1]}). '
            f'Vertex polynomials as coefficient lists in `t`, where `k = t + {K}`. Vertex `i` (1-based) is entry `i - 1`. -/\n')
    f.write(f'def {name}Verts : List (List Int) := [\n' + ',\n'.join('  ' + L(v) for v in V) + '\n]\n\n')
    f.write(f'/-- Edges `(u, v, w)` with `w = (k - 1) * u + v` identically. -/\n')
    f.write(f'def {name}Edges : List (Nat × Nat × Nat) := [\n' + ',\n'.join(f'  ({u}, {v}, {w})' for u, v, w in E) + '\n]\n\n')
    f.write(f'def {name}Reds : List Nat := {L(R)}\n\ndef {name}Blues : List Nat := {L(B)}\n\ndef {name}N : Nat := {len(V)}\n\nend RSN\n')
import segwriter
steps = segwriter.read_lrat(lrat)
nseg, nf = segwriter.write(name, N, steps, SEG, 10, f'RSN.Data.{N}', f'def {name}CNF : List Clause := caseCNF {name}N {name}Edges {name}Reds {name}Blues')
print('vertices', len(V), 'edges', len(E), 'reds', R, 'blues', B, 'steps', len(steps), 'segments', nseg, 'files', nf)
